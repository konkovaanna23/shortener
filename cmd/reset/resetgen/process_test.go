var content string = `
package main

// generate:reset
type FirstStruct struct {
    Name string
    Age  int
	Three *ThreeStruct
	
}

// generate:reset
type TwoStruct struct {
    Value []float64
	ValueMap map[int]int
}


// generate:reset
type ThreeStruct struct {
    Value int
}

func (t *ThreeStruct) Reset() {
	t.Value=0
}
`

